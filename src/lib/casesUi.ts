// Texto con `código` entre comillas invertidas → <code>. Escapa HTML primero.
export const rich = (s: string) =>
  s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[c as '&' | '<' | '>']).replace(/`([^`]+)`/g, '<code>$1</code>');
